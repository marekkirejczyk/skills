// The Markdown summary that goes in the PR comment, the top of the PR
// description and the CI job summary.
import { stats } from './load.mjs';

const dot = (passed, total) => (passed === total ? '🟢' : '🔴');
const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

// One line: the headline, used at the top of the PR description.
export function renderHeadline(report, { reportUrl = null, scope = null } = {}) {
  const totals = stats(report);
  const parts = [`${dot(totals.runsPassed, totals.runs)} **Evals: ${totals.runsPassed} / ${totals.runs} rounds passed** · ${totals.casesPassed} / ${totals.cases} cases`];
  if (scope) parts.push(`new or changed: ${totals.freshRunsPassed} / ${totals.freshRuns} rounds in ${totals.freshCases} cases`);
  if (reportUrl) parts.push(`[View report →](${reportUrl})`);
  return parts.join(' · ');
}

export function renderSummary(report, { reportUrl = null, scope = null, maxFailures = 15 } = {}) {
  const totals = stats(report);
  const lines = [`### ${dot(totals.runsPassed, totals.runs)} Eval report${reportUrl ? ` · [open the full report →](${reportUrl})` : ''}`, ''];
  lines.push(renderHeadline(report, { scope }), '');
  if (report.files.length) {
    lines.push('| File | Rounds | Cases | Failed cases |', '| --- | --- | --- | --- |');
    for (const file of report.files) {
      const failed = file.cases.filter((c) => !c.pass);
      const passedCases = file.cases.length - failed.length;
      lines.push(`| \`${cell(file.path)}\` | ${dot(file.runsPassed, file.runs)} ${file.runsPassed} / ${file.runs} | ${passedCases} / ${file.cases.length} | ${failed.length ? cell(failed.map((c) => c.name).join('; ')) : '—'} |`);
    }
    lines.push('');
  }
  const failures = report.files.flatMap((file) => file.cases.filter((c) => !c.pass).map((c) => ({ file, evalCase: c })));
  if (failures.length) {
    lines.push('<details><summary>Failed cases</summary>', '');
    for (const { evalCase } of failures.slice(0, maxFailures)) {
      const link = reportUrl ? `[${evalCase.name}](${reportUrl.replace(/#.*$/, '')}#${evalCase.id})` : evalCase.name;
      const fresh = evalCase.fresh ? ` _(${evalCase.fresh})_` : '';
      lines.push(`- 🔴 ${link}${fresh}: ${evalCase.runsPassed} / ${evalCase.runs.length} rounds`);
    }
    if (failures.length > maxFailures) lines.push(`- …and ${failures.length - maxFailures} more`);
    lines.push('', '</details>', '');
  }
  lines.push('<sub>Generated by eval-report · no model tokens used</sub>', '');
  return lines.join('\n');
}
