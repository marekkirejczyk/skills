// The numbers a report leads with, and the markdown that carries them to a
// pull request: a block at the top of its description and one sticky comment.

import { countRuns } from './results.mjs';

export const BODY_START = '<!-- eval-report:start -->';
export const BODY_END = '<!-- eval-report:end -->';
export const COMMENT_MARKER = '<!-- eval-report:comment -->';

const allRuns = (cases) => cases.flatMap((evalCase) => evalCase.runs);
const caseCount = (cases) => ({ passed: cases.filter((evalCase) => evalCase.passed).length, total: cases.length });

export function summarize(files, scope) {
  const cases = files.flatMap((file) => file.cases);
  const freshCases = cases.filter((evalCase) => evalCase.change);
  return {
    scope,
    runs: countRuns(allRuns(cases)),
    cases: caseCount(cases),
    fresh: scope === 'all' ? null : { runs: countRuns(allRuns(freshCases)), cases: caseCount(freshCases) },
    files: files.map((file) => ({
      path: file.path,
      runs: countRuns(allRuns(file.cases)),
      failedCases: file.cases.filter((evalCase) => !evalCase.passed).map((evalCase) => evalCase.name),
    })),
  };
}

const dot = ({ passed, total }) => (passed === total ? '🟢' : '🔴');
const ratio = ({ passed, total }) => `${passed} / ${total}`;

export function summaryLine(summary) {
  return `Evals: ${ratio(summary.runs)} runs passed · ${ratio(summary.cases)} cases`;
}

export function bodyBlock(summary, url) {
  const fresh = summary.fresh
    ? `\nNew or changed in this ${summary.scope === 'pr' ? 'PR' : 'commit'}: ${ratio(summary.fresh.cases)} cases, ${ratio(summary.fresh.runs)} runs passed`
    : '';
  return `${BODY_START}\n${dot(summary.runs)} **${summaryLine(summary)}** · [View report →](${url})${fresh}\n${BODY_END}`;
}

// Puts the block at the top of a PR description, replacing an earlier one.
export function upsertBodyBlock(body, block) {
  const text = body ?? '';
  const start = text.indexOf(BODY_START);
  const end = text.indexOf(BODY_END);
  if (start !== -1 && end > start) return text.slice(0, start) + block + text.slice(end + BODY_END.length);
  return text.trim() === '' ? block : `${block}\n\n${text}`;
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function commentBody(summary, url) {
  const rows = summary.files.map(
    (file) => `| ${dot(file.runs)} \`${cell(file.path)}\` | ${ratio(file.runs)} | ${cell(file.failedCases.join(' · ') || '—')} |`,
  );
  const failedLink = summary.runs.passed < summary.runs.total ? ` · [failed only](${url}#status=failed)` : '';
  return [
    COMMENT_MARKER,
    `### ${dot(summary.runs)} ${summaryLine(summary)}`,
    `[Open the full report →](${url})${failedLink}`,
    '',
    '| File | Runs passed | Failed cases |',
    '| --- | --- | --- |',
    ...rows,
    '',
    '<sub>Generated by eval-report, without model tokens.</sub>',
  ].join('\n');
}
